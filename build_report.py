def table(headers,rows,widths):
    t=doc.add_table(rows=1, cols=len(headers));t.autofit=False
    for i,w in enumerate(widths):t.columns[i].width=Cm(w)
    for i,v in enumerate(headers):t.rows[0].cells[i].text=str(v)
    for row in rows:
        cells=t.add_row().cells
        for i,v in enumerate(row):cells[i].text=str(v)
    for ri,row in enumerate(t.rows):
        trpr=row._tr.get_or_add_trPr()
        cant=OxmlElement("w:cantSplit");trpr.append(cant)
        if ri==0:
            repeat=OxmlElement("w:tblHeader");trpr.append(repeat)
        for ci,c in enumerate(row.cells):
            c.width=Cm(widths[ci]);pr=c._tc.get_or_add_tcPr()
            borders=OxmlElement("w:tcBorders")
            for edge in ["top","left","bottom","right"]:
                e=OxmlElement("w:"+edge);e.set(qn("w:val"),"single");e.set(qn("w:sz"),"4");e.set(qn("w:color"),"D8DDE4");borders.append(e)
            pr.append(borders)
            margins=OxmlElement("w:tcMar")
