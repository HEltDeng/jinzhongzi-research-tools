def fetch(s):
    dest=R/"sources"/(s["id"]+"_page.html")
    if dest.exists(): return s["id"]+" cached"
    p=subprocess.run(["curl","-L","--fail","--max-time","40","-sS",s["url"]],capture_output=True)
    if p.returncode: return s["id"]+" fetch failed"
    dest.write_bytes(p.stdout)
    try:
        tree=html.fromstring(p.stdout)
        for x in tree.xpath("//script|//style"): x.drop_tree()
        dest.with_suffix(".txt").write_text(tree.text_content(),encoding="utf-8")
    except Exception: pass
    return s["id"]+" archived"
